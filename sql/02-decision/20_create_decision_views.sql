CREATE OR REPLACE VIEW MARITIME_DEMO.MARITIME_SS_EXECUTIVE_V AS
SELECT
  d.INCIDENT_ID,
  d.INBOUND_VOYAGE_ID,
  d.PORT_CALL_ID,
  MAX(h.SELECTED_ETA_EVENT_ID) AS SELECTED_ETA_EVENT_ID,
  MAX(h.SELECTED_REVISION_NO) AS SELECTED_REVISION_NO,
  MAX(h.SELECTED_ETA_AT) AS SELECTED_ETA_AT,
  MAX(h.PRIOR_REPORTED_ETA_AT) AS PRIOR_REPORTED_ETA_AT,
  MAX(h.ETA_REVISION_DELTA_MINUTES) AS ETA_REVISION_DELTA_MINUTES,
  MAX(h.SCHEDULE_VARIANCE_MINUTES) AS SCHEDULE_VARIANCE_MINUTES,
  MAX(h.SOURCE_EVENT_AT) AS SELECTED_SOURCE_EVENT_AT,
  MAX(h.RECEIVED_AT) AS SELECTED_RECEIVED_AT,
  MAX(h.INGEST_LAG_MINUTES) AS INGEST_LAG_MINUTES,
  MAX(h.ADMITTED_EVENT_COUNT) AS ADMITTED_EVENT_COUNT,
  MAX(h.FUTURE_EVENT_EXCLUDED_COUNT) AS FUTURE_EVENT_EXCLUDED_COUNT,
  MAX(h.OUT_OF_ORDER_EVENT_COUNT) AS OUT_OF_ORDER_EVENT_COUNT,
  MAX(h.INGEST_STATUS) AS INGEST_STATUS,
  COUNT(*) AS ASSESSED_CONNECTION_COUNT,
  COUNT(DISTINCT d.CONTAINER_ID) AS CONTAINER_COUNT,
  COUNT(DISTINCT d.BOOKING_ID) AS BOOKING_COUNT,
  SUM(CASE WHEN d.DECISION_CODE = 'MISS' THEN 1 ELSE 0 END) AS MISS_COUNT,
  SUM(CASE WHEN d.DECISION_CODE = 'TIGHT' THEN 1 ELSE 0 END) AS TIGHT_COUNT,
  SUM(CASE WHEN d.DECISION_CODE = 'KEEP' THEN 1 ELSE 0 END) AS KEEP_COUNT,
  MAX(d.FIXTURE_VERSION) AS FIXTURE_VERSION,
  MAX(d.CONTRACT_VERSION) AS CONTRACT_VERSION,
  MAX(d.ONTOLOGY_VERSION) AS ONTOLOGY_VERSION,
  d.POLICY_VERSION,
  MAX(d.CONTEXT_SCENARIO_ID) AS CONTEXT_SCENARIO_ID,
  MAX(d.DATA_AS_OF_TS) AS DATA_AS_OF_TS,
  MAX(d.TIGHT_THRESHOLD_MIN) AS TIGHT_THRESHOLD_MIN,
  MAX(d.RUN_MODE) AS RUN_MODE,
  MAX(d.RESULT_PROVENANCE) AS RESULT_PROVENANCE,
  MAX(d.APPROVAL_STATE) AS APPROVAL_STATE,
  MAX(d.EXTERNAL_EXECUTION_YN) AS EXTERNAL_EXECUTION_YN,
  MAX(d.DATA_SCOPE) AS DATA_SCOPE
FROM MARITIME_DEMO.MARITIME_SS_CONNECTION_DECISION_V d
JOIN MARITIME_DEMO.MARITIME_SS_INGEST_HEALTH_V h
  ON h.PORT_CALL_ID = d.PORT_CALL_ID
 AND h.POLICY_VERSION = d.POLICY_VERSION
 AND h.FIXTURE_VERSION = d.FIXTURE_VERSION
GROUP BY
  d.INCIDENT_ID,
  d.INBOUND_VOYAGE_ID,
  d.PORT_CALL_ID,
  d.POLICY_VERSION;

COMMENT ON TABLE MARITIME_DEMO.MARITIME_SS_CONTEXT_V IS
  'Singleton synthetic demo provenance and manifest-bound policy context for deterministic replay.';
COMMENT ON TABLE MARITIME_DEMO.MARITIME_SS_LATEST_ETA_V IS
  'Latest admissible ETA for the manifest scenario port call at DATA_AS_OF_TS, selected by revision rather than receive order.';
COMMENT ON TABLE MARITIME_DEMO.MARITIME_SS_INGEST_HEALTH_V IS
  'Ledger replay quality, as-of selection, revision delta, schedule variance, and late-event evidence.';
COMMENT ON TABLE MARITIME_DEMO.MARITIME_SS_CONNECTION_DECISION_V IS
  'One row per eligible incident-scoped container connection with timestamps, slack, and manifest-bound policy result.';
COMMENT ON TABLE MARITIME_DEMO.MARITIME_SS_SEMANTIC_INPUT_V IS
  'Stable decision-support contract: one row per eligible assessed container connection with synthetic demo provenance.';
COMMENT ON TABLE MARITIME_DEMO.MARITIME_SS_EXECUTIVE_V IS
  'Single synthetic-demo summary: revision delta +420, schedule variance +420, 36 decisions, 9/6/21.';
COMMENT ON COLUMN MARITIME_DEMO.MARITIME_SS_CONNECTION_DECISION_V.CONNECTION_SLACK_MINUTES IS
  'Rounded display value: terminal cutoff minus estimated ready time. Timestamp instants, not this rounded value, drive classification.';
COMMENT ON COLUMN MARITIME_DEMO.MARITIME_SS_CONNECTION_DECISION_V.DECISION_CODE IS
  'Closed-world policy result. MISS is not proof that a transshipment failure has completed.';

