DECLARE
  l_table_count                NUMBER;
  l_named_constraint_count     NUMBER;
  l_bad_constraint             NUMBER;
  l_manifest_incident_fk_ok    NUMBER;
  l_connection_booking_fk_ok   NUMBER;
  l_policy_index_ok            NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO l_table_count
    FROM USER_TABLES
   WHERE TABLE_NAME IN (
     'MARITIME_SS_DEMO_CLOCK', 'MARITIME_SS_POLICY_VERSIONS', 'MARITIME_SS_FIXTURE_MANIFEST',
     'MARITIME_SS_VESSELS', 'MARITIME_SS_VOYAGES', 'MARITIME_SS_PORTS', 'MARITIME_SS_PORT_CALLS',
     'MARITIME_SS_ETA_EVENTS', 'MARITIME_SS_TERMINAL_CUTOFFS', 'MARITIME_SS_INCIDENTS',
     'MARITIME_SS_BOOKINGS', 'MARITIME_SS_CONTAINERS', 'MARITIME_SS_BOOKING_CONTAINERS',
     'MARITIME_SS_CONNECTIONS'
   );

  SELECT COUNT(*)
    INTO l_named_constraint_count
    FROM USER_CONSTRAINTS
   WHERE CONSTRAINT_NAME LIKE 'MARITIME\_SS\_%' ESCAPE '\';

  SELECT COUNT(*)
    INTO l_bad_constraint
    FROM USER_CONSTRAINTS
   WHERE CONSTRAINT_NAME LIKE 'MARITIME\_SS\_%' ESCAPE '\'
     AND (STATUS <> 'ENABLED' OR VALIDATED <> 'VALIDATED');

  SELECT COUNT(*)
    INTO l_manifest_incident_fk_ok
    FROM USER_CONSTRAINTS
   WHERE CONSTRAINT_NAME = 'MARITIME_SS_MANIFEST_INCIDENT_FK'
     AND TABLE_NAME = 'MARITIME_SS_FIXTURE_MANIFEST'
     AND CONSTRAINT_TYPE = 'R'
     AND STATUS = 'ENABLED'
     AND VALIDATED = 'VALIDATED'
     AND DEFERRABLE = 'DEFERRABLE'
     AND DEFERRED = 'DEFERRED';

  SELECT COUNT(*)
    INTO l_connection_booking_fk_ok
    FROM USER_CONSTRAINTS
   WHERE CONSTRAINT_NAME = 'MARITIME_SS_CONN_BOOKING_EDGE_FK'
     AND TABLE_NAME = 'MARITIME_SS_CONNECTIONS'
     AND CONSTRAINT_TYPE = 'R'
     AND STATUS = 'ENABLED'
     AND VALIDATED = 'VALIDATED';

  SELECT COUNT(*)
    INTO l_policy_index_ok
    FROM USER_INDEXES
   WHERE INDEX_NAME = 'MARITIME_SS_POLICY_ONE_ACTIVE_UI'
     AND STATUS = 'VALID'
     AND UNIQUENESS = 'UNIQUE';

  IF l_table_count <> 14
     OR l_named_constraint_count <> 77
     OR l_bad_constraint <> 0
     OR l_manifest_incident_fk_ok <> 1
     OR l_connection_booking_fk_ok <> 1
     OR l_policy_index_ok <> 1 THEN
    RAISE_APPLICATION_ERROR(
      -20002,
      'DDL postcondition failed: tables=' || l_table_count
      || ', named_constraints=' || l_named_constraint_count
      || ', bad_constraints=' || l_bad_constraint
      || ', manifest_incident_fk=' || l_manifest_incident_fk_ok
      || ', connection_booking_fk=' || l_connection_booking_fk_ok
      || ', active_policy_index=' || l_policy_index_ok
    );
  END IF;

  DBMS_OUTPUT.PUT_LINE('PASS MARITIME_SS relational DDL created and validated');
END;
