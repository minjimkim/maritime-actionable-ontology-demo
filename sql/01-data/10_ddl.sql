-- Maritime Actionable Ontology Demo Kit
-- Relational source-of-record contract. Empty MARITIME_SS_* namespace only.

SET SERVEROUTPUT ON

DECLARE
  l_user          VARCHAR2(128) := UPPER(SYS_CONTEXT('USERENV', 'SESSION_USER'));
  l_schema        VARCHAR2(128) := UPPER(SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA'));
  l_object_count  NUMBER;
BEGIN
  IF l_user <> 'MARITIME_DEMO' OR l_schema <> 'MARITIME_DEMO' THEN
    RAISE_APPLICATION_ERROR(
      -20000,
      'Safety stop: connect directly as MARITIME_DEMO.'
    );
  END IF;

  SELECT COUNT(*)
    INTO l_object_count
    FROM USER_OBJECTS
   WHERE OBJECT_NAME LIKE 'MARITIME\_SS\_%' ESCAPE '\';

  IF l_object_count <> 0 THEN
    RAISE_APPLICATION_ERROR(
      -20001,
      'MARITIME_SS_* namespace is not empty. Existing objects are never deleted automatically.'
    );
  END IF;
END;
