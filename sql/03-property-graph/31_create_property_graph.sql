    INTO l_valid_graph_count
    FROM USER_OBJECTS
   WHERE OBJECT_NAME = 'MARITIME_SS_SHIP_SHORE_G'
     AND OBJECT_TYPE = 'PROPERTY GRAPH'
     AND STATUS = 'VALID';

  IF l_valid_graph_count <> 1 THEN
    RAISE_APPLICATION_ERROR(
      -20320,
      'Property Graph postcondition failed: valid_graphs=' || l_valid_graph_count
    );
  END IF;

  DBMS_OUTPUT.PUT_LINE('PASS MARITIME_SS Property Graph created and valid');
END;
